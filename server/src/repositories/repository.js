/**
 * Repository layer — shared contract.
 *
 * The services own business rules and know nothing about a database. Everything
 * that touches storage sits behind a repository with one of the interfaces
 * declared in this folder, and two implementations must exist for each:
 *
 *   repositories/mongo/<domain>.repository.js   ← Mongoose (reference implementation)
 *   repositories/mysql/<domain>.repository.js   ← mysql2
 *
 * Invariants every implementation must honour (they are what makes the two
 * providers interchangeable):
 *  1. **Canonical ids.** Values crossing the boundary are 24-character lowercase
 *     hex strings generated by `utils/id.js`. No `ObjectId`, no `Buffer`, no
 *     driver-specific identity object may leave a repository.
 *  2. **Plain data in, plain data out.** No driver row/document objects, no
 *     `ResultSetHeader`, no `affectedRows` / `__v` / `_id` leaking upward. Derived
 *     presentation fields are produced by `repositories/product.mapper.js`.
 *  3. **Money is a `number`** rounded to 2 decimals (`DECIMAL(12,2)` on MySQL),
 *     never a string, never a float-formatting difference.
 *  4. **Dates are `Date` objects** in UTC, serialised as ISO-8601 `…Z` by Express.
 *  5. **`null`, never `undefined`**, for absent optional fields (`sku`, `lockedUntil`…).
 *  6. **Errors are normalised** to `ApiError` with the codes the API already
 *     publishes (`DUPLICATE_KEY`, `STALE_RESOURCE`, `PRODUCT_NOT_FOUND`, …) so the
 *     same failure produces the same payload on both providers.
 *  7. **No transaction requirement.** Atomicity comes from single-document atomic
 *     operators (MongoDB `$inc` with a guard) or a single guarded `UPDATE`
 *     (MySQL), both of which are one statement — see decision D2(a).
 *
 * @typedef {object} PublicProduct
 * @property {string} id
 * @property {string} title
 * @property {string} slug
 * @property {string | null} sku
 * @property {number} price
 * @property {number} stock
 * @property {boolean} inStock
 * @property {'out_of_stock' | 'low_stock' | 'in_stock'} stockStatus
 * @property {string} description
 * @property {string} image
 * @property {string} thumbnail
 * @property {{ id: string, name: string, slug: string } | null} brand
 * @property {{ id: string, name: string, slug: string } | null} category
 * @property {boolean} isActive
 * @property {Date} createdAt
 * @property {Date} updatedAt
 *
 * @typedef {PublicProduct & { version: number }} AdminProduct
 *
 * @typedef {object} CursorPage
 * @property {PublicProduct[]} items
 * @property {{ limit: number, count: number, sort: string, hasNextPage: boolean, nextCursor: string | null }} meta
 *
 * @typedef {object} OffsetPage
 * @property {AdminProduct[]} items
 * @property {{ page: number, limit: number, total: number, totalPages: number }} meta
 */

/**
 * Asserts that an implementation provides every method of its contract.
 *
 * Used by the provider factory so a wiring mistake fails at startup with a clear
 * message instead of producing `undefined is not a function` at request time.
 *
 * @template T
 * @param {string} name  contract name, e.g. `products`
 * @param {readonly string[]} requiredMethods
 * @param {T} implementation
 * @returns {T}
 */
export function defineRepository(name, requiredMethods, implementation) {
  if (!implementation || typeof implementation !== 'object') {
    throw new TypeError(`Repository "${name}" must be an object`);
  }
  const missing = requiredMethods.filter((method) => typeof implementation[method] !== 'function');
  if (missing.length > 0) {
    throw new TypeError(`Repository "${name}" is missing: ${missing.join(', ')}`);
  }
  return implementation;
}

export default { defineRepository };
